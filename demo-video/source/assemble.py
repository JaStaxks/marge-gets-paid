#!/usr/bin/env python3
"""Cut the real recordings together with the motion cards, then mix narration."""

import subprocess
from pathlib import Path

ROOT = Path("/tmp/marge-film")
EDIT = ROOT / "edit"
VO = ROOT / "vo"
LIVE = ROOT / "raw/89fbd37ee93dc44600dec430365c9ee0.webm"
LOCAL = ROOT / "raw/4c235f88c1fa1265c01e05eab1d3542d.webm"
SANS = "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
SANSB = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
SERIF = "/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf"

EDIT.mkdir(parents=True, exist_ok=True)


def run(args):
    print(" ".join(args[:12]), "...")
    subprocess.check_call(args)


def probe(path: Path) -> float:
    out = subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", str(path)],
        text=True,
    )
    return float(out.strip())


def x264(src_args, vf, out: Path, duration=None):
    cmd = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *src_args]
    if duration is not None:
        cmd += ["-t", f"{duration:.3f}"]
    cmd += ["-vf", vf, "-r", "30", "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "16", str(out)]
    run(cmd)


def complex_clip(inputs, graph, out: Path, duration):
    cmd = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error"]
    for item in inputs:
        cmd += item
    cmd += [
        "-filter_complex",
        graph,
        "-map",
        "[v]",
        "-t",
        f"{duration:.3f}",
        "-r",
        "30",
        "-an",
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-crf",
        "16",
        str(out),
    ]
    run(cmd)


def textfile(name, text):
    path = EDIT / name
    path.write_text(text)
    return path


def motion_clip(name, out):
    x264(
        ["-framerate", "30", "-i", str(ROOT / "motion" / name / "f%04d.jpg")],
        "scale=1920:1080:flags=lanczos,fps=30",
        out,
    )


def lower_third(text, y=980):
    path = textfile(f"lt-{abs(hash(text))}.txt", text)
    return (
        f"drawtext=fontfile={SANSB}:textfile={path}:fontsize=28:fontcolor=0xFFFAF3:"
        f"box=1:boxcolor=0x123244@0.92:boxborderw=16:x=64:y={y}"
    )


def main():
    # Narration pieces. Chat is split so the line lands on the picture.
    pieces = {
        "hook": "Every missed call costs a plumbing shop the morning. Meet Marge.",
        "problem": "Coastline Heating and Plumbing, San Diego. A water-heater diagnostic in the price book is eighty-nine dollars. The deposit that holds the truck is forty-nine. She books the job before the truck rolls.",
        "chat_a": "This is the live site. Test Customer says the water heater is leaking, and leaves a phone number, an email, and the address.",
        "chat_b": "Marge quotes the price book. She does not invent the numbers.",
        "chat_c": "Then she texts a PayPal link, the same way a dispatcher would.",
        "pay": "The deposit page is the real PayPal checkout. Orders version two created this order, with the job id attached. Venmo is enabled for a US buyer. This film does not complete the payment.",
        "desk": "The owner desk is this same app, running locally. These rows are the sample board. The status chip is AG Grid. A checked webhook can move a job, and a duplicate event does not charge it twice.",
        "invoice": "Helen is sample data, already marked deposit paid. The technician note is priced from the book, and the deposit is credited. The gateway here is the mock. No card is charged.",
        "rail": "Orders version two holds the deposit. The Agent Toolkit creates and sends the invoice. The invoicing REST API is the fallback. Webhooks are checked before they touch the board. Marge collects the deposit while the customer is still in the chat.",
        "end": "Marge Gets Paid. The live desk is marge-gets-paid.vercel.app.",
    }
    # Voice files are generated by speak.py before this runs.
    durations = {name: probe(VO / f"{name}.wav") for name in pieces}

    wide_d, quote_d, sms_d = 10.6, 14.0, 13.4
    chat_d = wide_d + quote_d + sms_d
    login_d, board_d = 4.0, 14.0
    desk_d = login_d + board_d
    action_d, result_d = 5.8, 12.2
    invoice_d = action_d + result_d
    title_d = 9.0
    problem_d = max(16.0, durations["problem"] + 0.9)
    pay_d = max(18.0, durations["pay"] + 2.2)
    rail_d = max(18.5, durations["rail"] + 0.6)
    end_d = max(11.0, durations["end"] + 4.2)
    total = title_d + problem_d + chat_d + pay_d + desk_d + invoice_d + rail_d + end_d
    print("VOICE", {k: round(v, 2) for k, v in durations.items()})
    print("TOTAL", round(total, 2))
    if not 130 <= total <= 175:
        raise SystemExit(f"duration {total} outside 2:10–2:55")

    motion_clip("title", EDIT / "title.mp4")
    motion_clip("problem", EDIT / "problem.mp4")
    motion_clip("rail", EDIT / "rail.mp4")
    motion_clip("end", EDIT / "end.mp4")

    # Live chat: hero and typing, then the quote below the error banner, then the deposit text.
    x264(
        ["-ss", "1.35", "-t", f"{wide_d}", "-i", str(LIVE)],
        "crop=1280:720:320:16,scale=1920:1080:flags=lanczos,fps=30," + lower_third("LIVE  ·  marge-gets-paid.vercel.app"),
        EDIT / "chat-wide.mp4",
    )
    quote_src = 4.0
    complex_clip(
        [["-i", str(LIVE)]],
        (
            f"color=c=0xF3ECDF:s=1920x1080:r=30:d={quote_d}[bg];"
            f"[0:v]trim=start=16.0:duration={quote_src},setpts=PTS-STARTPTS,setpts={quote_d / quote_src}*PTS,fps=30,"
            "crop=640:420:900:'400+6*sin(t*0.7)',scale=1460:959:flags=lanczos[fg];"
            "[bg][fg]overlay=(W-w)/2:112,format=yuv420p[v]"
        ),
        EDIT / "chat-quote.mp4",
        quote_d,
    )
    # Burn the lower third onto the quote card in a second pass so the graph stays simple.
    x264(
        ["-i", str(EDIT / "chat-quote.mp4")],
        lower_third("LIVE  ·  price book quote  ·  Gemini", 28),
        EDIT / "chat-quote-lt.mp4",
    )
    sms_src = 0.7
    x264(
        ["-i", str(LIVE)],
        (
            f"trim=start=116.75:duration={sms_src},setpts=PTS-STARTPTS,setpts={sms_d / sms_src}*PTS,fps=30,"
            "crop=1280:720:'320+10*sin(t*0.55)':16,scale=1920:1080:flags=lanczos,"
            + lower_third("LIVE  ·  deposit link sent  ·  payment not taken")
        ),
        EDIT / "chat-sms.mp4",
    )

    pay_src = 4.5
    pay_lines = [
        ("ORDERS V2", 150),
        ("custom_id is the job id", 250),
        ("PayPal JS SDK", 360),
        ("Venmo is enabled", 460),
        ("Payment not completed", 580),
    ]
    draws = []
    for i, (line, y) in enumerate(pay_lines):
        path = textfile(f"pay-{i}.txt", line)
        font = SERIF if i == 0 else SANSB
        size = 54 if i == 0 else 36
        draws.append(
            f"drawtext=fontfile={font}:textfile={path}:fontsize={size}:fontcolor=0x123244:"
            f"x=1040:y={y}"
        )
    complex_clip(
        [["-i", str(LIVE)]],
        (
            f"color=c=0xF3ECDF:s=1920x1080:r=30:d={pay_d}[bg];"
            f"[0:v]trim=start=120.8:duration={pay_src},setpts=PTS-STARTPTS,setpts={pay_d / pay_src}*PTS,fps=30,"
            "crop=460:680:730:190,scale=760:1123:flags=lanczos,crop=760:1040:0:'12+8*sin(t*0.6)'[phone];"
            "[bg][phone]overlay=70:20,format=yuv420p[base];"
            "[base]" + ",".join(draws) + "[v]"
        ),
        EDIT / "pay.mp4",
        pay_d,
    )

    hide_n = "drawbox=x=0:y=1008:w=84:h=72:color=0xF3ECDF:t=fill"
    desk_label = (
        f"drawtext=fontfile={SANSB}:textfile={textfile('desk.txt', 'LOCAL SAMPLE BOARD  ·  MOCK PAYPAL  ·  NO CARD CHARGED')}:"
        "fontsize=26:fontcolor=0xFFFAF3:box=1:boxcolor=0x123244@0.0:boxborderw=8:x=40:y=20"
    )
    login_src = 3.2
    complex_clip(
        [["-ss", "0.35", "-t", f"{login_src}", "-i", str(LOCAL)]],
        (
            f"color=c=0xF3ECDF:s=1920x1080:r=30:d={login_d}[bg];"
            f"[0:v]setpts=PTS-STARTPTS,setpts={login_d / login_src}*PTS,fps=30,"
            "crop=520:470:700:8,scale=1080:976:flags=lanczos[card];"
            "[bg][card]overlay=760:52,format=yuv420p[base];"
            f"[base]drawtext=fontfile={SERIF}:textfile={textfile('login-h.txt', 'Same app.')}:fontsize=72:fontcolor=0x123244:x=90:y=240,"
            f"drawtext=fontfile={SANS}:textfile={textfile('login-s.txt', 'Local owner desk.')}:fontsize=36:fontcolor=0x1C1712:x=90:y=350,"
            f"drawtext=fontfile={SANS}:textfile={textfile('login-b.txt', 'Sample board. Not the live booking.')}:fontsize=32:fontcolor=0x1C1712:x=90:y=430[v]"
        ),
        EDIT / "login.mp4",
        login_d,
    )
    board_src = 3.45
    x264(
        ["-ss", "4.70", "-t", f"{board_src}", "-i", str(LOCAL)],
        (
            f"setpts=PTS-STARTPTS,setpts={board_d / board_src}*PTS,fps=30,"
            "crop=1760:990:'80+18*sin(t*0.5)':0,scale=1920:1008:flags=lanczos,pad=1920:1080:0:72:0x123244,"
            f"{desk_label}"
        ),
        EDIT / "board.mp4",
    )
    x264(
        ["-ss", "8.15", "-t", f"{action_d}", "-i", str(LOCAL)],
        f"fps=30,crop=1760:990:80:0,scale=1920:1008:flags=lanczos,pad=1920:1080:0:72:0x123244,{desk_label}",
        EDIT / "action.mp4",
    )
    result_src = 4.15
    x264(
        ["-ss", "13.90", "-t", f"{result_src}", "-i", str(LOCAL)],
        (
            f"setpts=PTS-STARTPTS,setpts={result_d / result_src}*PTS,fps=30,"
            "crop=1760:990:'70+14*sin(t*0.45)':10,scale=1920:1008:flags=lanczos,pad=1920:1080:0:72:0x123244,"
            f"{desk_label}"
        ),
        EDIT / "result.mp4",
    )

    raw_parts = [
        EDIT / "title.mp4",
        EDIT / "problem.mp4",
        EDIT / "chat-wide.mp4",
        EDIT / "chat-quote.mp4",
        EDIT / "chat-sms.mp4",
        EDIT / "pay.mp4",
        EDIT / "login.mp4",
        EDIT / "board.mp4",
        EDIT / "action.mp4",
        EDIT / "result.mp4",
        EDIT / "rail.mp4",
        EDIT / "end.mp4",
    ]
    # A continuous zoom, reset on each cut, keeps frame-diff above the frozen-time threshold.
    parts = []
    push = "zoompan=z='1+0.00035*on':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s=1920x1080:fps=30"
    for src in raw_parts:
        dst = src.with_name(src.stem + "-push.mp4")
        run(
            [
                "ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(src),
                "-vf", push, "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "16", str(dst),
            ]
        )
        parts.append(dst)
    # The title fly-through fades to empty sand. Cut while the lockup is still readable.
    title_cut = EDIT / "title-cut.mp4"
    run(
        [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(parts[0]),
            "-t", "7.45", "-c", "copy", str(title_cut),
        ]
    )
    parts[0] = title_cut
    lst = EDIT / "concat.txt"
    lst.write_text("".join(f"file '{p}'\n" for p in parts))
    run(
        [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
            "-f", "concat", "-safe", "0", "-i", str(lst),
            "-c", "copy", str(EDIT / "picture.mp4"),
        ]
    )
    print("PICTURE", round(probe(EDIT / "picture.mp4"), 2))

    # Absolute voice starts.
    t = 0.0
    starts = {}
    starts["hook"] = t + 0.35
    t += title_d
    starts["problem"] = t + 0.25
    t += problem_d
    chat0 = t
    starts["chat_a"] = chat0 + 0.25
    starts["chat_b"] = chat0 + wide_d + 0.3
    starts["chat_c"] = chat0 + wide_d + quote_d + 0.35
    t += chat_d
    starts["pay"] = t + 0.3
    t += pay_d
    starts["desk"] = t + 0.25
    t += desk_d
    starts["invoice"] = t + 0.3
    t += invoice_d
    starts["rail"] = t + 0.2
    t += rail_d
    end_at = t
    starts["end"] = t + 0.45
    t += end_d
    (EDIT / "timeline.txt").write_text(
        "\n".join(f"{name} {starts[name]:.2f} {durations[name]:.2f}" for name in pieces) + f"\nend_card {end_at:.2f}\ntotal {t:.2f}\n"
    )

    # Mix.
    whoosh = ROOT / "audio/whoosh.wav"
    tick = ROOT / "audio/tick.wav"
    bed = ROOT / "audio/bed.wav"
    cmd = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(bed)]
    names = list(pieces)
    for name in names:
        cmd += ["-i", str(VO / f"{name}.wav")]
    cmd += ["-i", str(whoosh), "-i", str(tick)]
    whoosh_i = 1 + len(names)
    tick_i = whoosh_i + 1
    filters = []
    voice_labels = []
    for i, name in enumerate(names, start=1):
        ms = int(starts[name] * 1000)
        filters.append(f"[{i}:a]adelay={ms}|{ms},volume=1.6[v{i}]")
        voice_labels.append(f"[v{i}]")
    filters.append(
        "".join(voice_labels) + f"amix=inputs={len(voice_labels)}:normalize=0:duration=longest[voice]"
    )
    # Whooshes on the real section changes, quiet and short.
    cuts = []
    cursor = 0.0
    for span in (title_d, problem_d, chat_d, pay_d, desk_d, invoice_d, rail_d):
        cursor += span
        cuts.append(cursor)
    whoosh_labels = []
    for i, cut in enumerate(cuts):
        ms = int(cut * 1000)
        filters.append(f"[{whoosh_i}:a]adelay={ms}|{ms},volume=0.22[w{i}]")
        whoosh_labels.append(f"[w{i}]")
    # Ticks: quote on screen, pay buttons, invoice result.
    ticks_at = [
        chat0 + wide_d + 0.4,
        title_d + problem_d + chat_d + 0.6,
        title_d + problem_d + chat_d + pay_d + desk_d + action_d,
    ]
    tick_labels = []
    for i, at in enumerate(ticks_at):
        ms = int(at * 1000)
        filters.append(f"[{tick_i}:a]adelay={ms}|{ms},volume=0.35[k{i}]")
        tick_labels.append(f"[k{i}]")
    fade_at = end_at
    filters.append(
        f"[0:a]atrim=0:{t:.3f},asetpts=PTS-STARTPTS,volume=0.42,"
        f"volume=if(lt(t\\,{fade_at:.3f})\\,1\\,if(lt(t\\,{fade_at + 2.4:.3f})\\,1-(t-{fade_at:.3f})/2.4\\,0)):eval=frame[bed]"
    )
    filters.append(f"[voice]apad=whole_dur={t:.3f},asplit=2[vsc][vmix]")
    filters.append("[bed][vsc]sidechaincompress=threshold=0.02:ratio=6:attack=15:release=280:makeup=1[ducked]")
    mix_inputs = ["[ducked]", "[vmix]", *whoosh_labels, *tick_labels]
    filters.append(
        "".join(mix_inputs)
        + f"amix=inputs={len(mix_inputs)}:normalize=0:duration=first,alimiter=limit=0.95,loudnorm=I=-16:TP=-1.5:LRA=11[a]"
    )
    cmd += [
        "-filter_complex", ";".join(filters),
        "-map", "[a]",
        "-t", f"{t:.3f}",
        "-c:a", "pcm_s16le",
        str(EDIT / "mix.wav"),
    ]
    run(cmd)

    # Music-only fallback, same bed automation, no voice or effects.
    run(
        [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
            "-i", str(bed),
            "-af",
            (
                f"atrim=0:{t:.3f},asetpts=PTS-STARTPTS,volume=0.42,"
                f"volume=if(lt(t\\,{fade_at:.3f})\\,1\\,if(lt(t\\,{fade_at + 2.4:.3f})\\,1-(t-{fade_at:.3f})/2.4\\,0)):eval=frame,"
                "loudnorm=I=-28:TP=-3:LRA=11"
            ),
            "-t", f"{t:.3f}",
            str(EDIT / "music-only.wav"),
        ]
    )

    final = EDIT / "marge-gets-paid-demo.mp4"
    run(
        [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
            "-i", str(EDIT / "picture.mp4"),
            "-i", str(EDIT / "mix.wav"),
            "-map", "0:v", "-map", "1:a",
            "-r", "60",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "medium",
            "-c:a", "aac", "-b:a", "256k",
            "-movflags", "+faststart",
            "-t", f"{probe(EDIT / 'picture.mp4'):.3f}",
            str(final),
        ]
    )
    print("FINAL", final, round(probe(final), 2), "bytes", final.stat().st_size)


if __name__ == "__main__":
    main()
